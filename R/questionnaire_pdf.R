# ---------------------------------------------------------------------------
# questionnaire_pdf.R -- EXPERIMENTAL reader for Designer PDF printouts.
#
# The PDF layout interleaves table columns when converted to text, so this is
# heuristic. Every HQ export archive contains Questionnaire/content.zip with
# the exact document.json -- prefer that (or Designer's JSON download).
#
# Recognised markers (Designer "PDF" printout, 2023-2024 layout):
#   <text> <TYPE> <var>         question line (TYPE e.g. NUMERIC: INTEGER)
#   NN Label                    option / fixed roster title
#   E <expr>                    enabling condition (inline, may be truncated)
#   V1 <expr> / W1 <expr>       validation error / warning; M1 <msg> message
#   SCOPE: HIDDEN|SUPERVISOR|IDENTIFYING
#   Roster: <title>  +  generated by <list|multi-select|numeric|yes/no> question <var> <name>
#                    |  generated by fixed list <name>
#   APPENDIX A -- full enabling conditions keyed by "[n] VAR:"
# Nesting of rosters is taken from the page breadcrumbs ("SECTION / ROSTER / ROSTER").
# ---------------------------------------------------------------------------

.pdf_types <- c("NUMERIC: INTEGER" = "NumericQuestion|int", "NUMERIC: DECIMAL" = "NumericQuestion|dec",
  "SINGLE-SELECT" = "SingleQuestion", "MULTI-SELECT" = "MultyOptionsQuestion", "TEXT" = "TextQuestion",
  "DATE" = "DateTimeQuestion", "GPS" = "GpsCoordinateQuestion", "LIST" = "TextListQuestion",
  "PICTURE" = "MultimediaQuestion", "BARCODE" = "QRBarcodeQuestion", "AUDIO" = "AudioQuestion",
  "AREA" = "AreaQuestion", "NUMERIC" = "NumericQuestion|dec")

pdf_lines <- function(path, engine) {
  txt <- if (engine == "markitdown") {
    out <- tryCatch(system2("markitdown", shQuote(path), stdout = TRUE, stderr = FALSE), error = function(e) NULL)
    if (is.null(out) || !length(out)) stop("markitdown CLI not available; use pdf_engine = 'pdftools'", call. = FALSE)
    out
  } else {
    check_dependencies(pdf = TRUE)
    unlist(strsplit(pdftools::pdf_text(path), "\n"))
  }
  txt <- txt[!grepl("^\\s*([0-9]+\\s*)?/\\s*[0-9]+\\s*$", txt)]   # page footers "6 / 23"
  l <- gsub("\\|", " ", txt)
  l <- gsub("-{3,}", " ", l)
  trimws(gsub("[ \t]+", " ", l))
}

suso_read_pdf <- function(path, engine = "pdftools", verbose = TRUE) {
  sm_msg(verbose, "Reading questionnaire PDF (EXPERIMENTAL; prefer document.json): ", basename(path))
  L <- pdf_lines(path, engine)
  L <- L[nzchar(L)]
  app <- grep("^APPENDIX A", L)
  if (length(app) > 1 && grepl("CATEGORIES", L[app[2]])) app <- app[1]   # appendix A holds categories, not conditions
  body_end <- if (length(app) > 1) app[2] - 1 else length(L)
  apx_end <- grep("^APPENDIX B", L); apx_end <- if (length(apx_end) > 1) apx_end[2] - 1 else length(L)
  # full conditions from appendix A
  full_cond <- list()
  if (length(app) > 1) {
    A <- L[(app[2] + 1):apx_end]
    hd <- grep("^\\[[0-9]+\\] ", A)
    for (k in seq_along(hd)) {
      stop_at <- if (k < length(hd)) hd[k + 1] - 1 else length(A)
      key <- sub("^\\[[0-9]+\\] ([A-Za-z0-9_]*) ?:.*$", "\\1", A[hd[k]])
      ttl <- trimws(sub("^\\[[0-9]+\\] [A-Za-z0-9_]* ?: ?", "", A[hd[k]]))
      seg <- A[(hd[k] + 1):stop_at]
      seg <- seg[!grepl("^Enablement Condition:|^[0-9]+$|^/ [0-9]+$|^[0-9]+ / [0-9]+$", seg)]
      full_cond[[if (nzchar(key)) key else paste0("roster::", toupper(ttl))]] <- paste(seg, collapse = "\n")
    }
  }
  sections <- character()
  toc_end <- grep("^APPENDIX A", L)[1]
  i <- 1
  while (i < toc_end) {
    if (grepl("^(No sub-sections|Sub-sections:)", L[i + 1] %||% "")) sections <- c(sections, L[i])
    i <- i + 1
  }
  type_rx <- paste0("\\b(", paste(gsub("([-:])", "\\1", names(.pdf_types)), collapse = "|"), ")(: [A-Z /-]+)?\\b")
  id <- 0L; nid <- function() { id <<- id + 1L; sprintf("%032x", id) }
  doc <- list(Title = sub("\\.pdf$", "", basename(path)), VariableName = gsub("[^A-Za-z0-9_]", "_", sub("\\.pdf$", "", basename(path))), Children = list())
  # flat item list with nesting info; assembled into a tree at the end
  items <- list(); cur_q <- NULL; cur_sec <- NULL; roster_stack <- list(); last_roster <- NULL; pending_fixed <- FALSE
  var_ids <- list()
  push <- function(it) { items[[length(items) + 1]] <<- it; length(items) }
  start <- grep("^SURVEY IDENTIFICATION INFORMATION$", L); start <- if (length(start) > 1) start[2] else 1
  # an expression wrapped over lines: join while a string or a parenthesis is open
  unwrap <- function(i, x = L[i]) {
    j <- i
    open_q <- function(x) nchar(gsub('[^"]', "", x)) %% 2 == 1
    open_p <- function(x) nchar(gsub("[^(]", "", x)) > nchar(gsub("[^)]", "", x))
    while ((open_q(x) || open_p(x)) && j < body_end && j - i < 4) {
      j <- j + 1; x <- paste0(x, if (open_q(x)) " " else "", L[j])   # trimmed space inside literals, mid-word breaks outside
    }
    list(x = x, skip = if (j > i) j else skip)
  }
  skip <- 0L; instr <- FALSE                                         # previous line was an "I" instruction (or its wrap)
  for (i in start:body_end) {
    if (i <= skip) next
    ln <- L[i]
    cont <- instr && !grepl("^([EVWMI] |[VWM][0-9]|Roster: )", ln) && !grepl(type_rx, ln, perl = TRUE)
    instr <- cont
    if (ln %in% sections) {
      cur_sec <- push(list(kind = "section", title = ln, id = nid(), parent = NA)); roster_stack <- list(); cur_q <- NULL; next
    }
    if (grepl("/", ln) && !grepl("[()=<>]", ln)) {        # breadcrumb: SECTION / R1 / R2
      parts <- trimws(strsplit(ln, "/")[[1]])
      if (parts[1] %in% sections) {                      # "/" inside question text is not a breadcrumb
        titles <- toupper(parts[-1])
        roster_stack <- Filter(function(r) toupper(items[[r]]$title) %in% titles |
                                 sub(" - %ROSTERTITLE%$", "", toupper(items[[r]]$title)) %in% titles, roster_stack)
        next
      }
    }
    if (grepl("^Roster: ", ln)) {
      ttl <- sub("^Roster: ", "", ln)
      gen <- L[i + 1] %||% ""
      it <- list(kind = "roster", title = ttl, id = nid(), parent = if (length(roster_stack)) roster_stack[[length(roster_stack)]] else cur_sec,
                 src = "fixed", trig = NA, name = NA, titles = list())
      m <- regmatches(gen, regexec("generated by (list|multi-select|numeric|yes/no) question ([A-Za-z0-9_]+) ([A-Za-z0-9_]+)", gen))[[1]]
      if (length(m)) { it$src <- "question"; it$trig <- m[3]; it$name <- m[4] }
      m2 <- regmatches(gen, regexec("generated by fixed list ([A-Za-z0-9_]+)", gen))[[1]]
      if (length(m2)) { it$name <- m2[2]; pending_fixed <- TRUE }
      it$cond <- full_cond[[paste0("roster::", toupper(ttl))]] %||% ""
      last_roster <- push(it); roster_stack[[length(roster_stack) + 1]] <- last_roster; cur_q <- NULL
      next
    }
    if (grepl("^generated by ", ln)) next
    # option printed at the end of a wrapped line ("...text 01 Yes", "E cond 00 No"); codes are zero-padded
    tail_opt <- regmatches(ln, regexec("^(.*\\S)\\s+(-?[0-9]{2,6}) ([A-Za-z].{0,60})$", ln))[[1]]
    if (length(tail_opt) && !is.null(cur_q) && !pending_fixed && !grepl("^M[0-9]", ln) && !grepl(type_rx, ln, perl = TRUE) &&
        items[[cur_q]]$cls %in% c("SingleQuestion", "MultyOptionsQuestion")) {
      items[[cur_q]]$opts[[length(items[[cur_q]]$opts) + 1]] <- list(AnswerValue = tail_opt[3], AnswerText = tail_opt[4])
      ln <- tail_opt[2]
    }
    tm <- regmatches(ln, regexec(type_rx, ln, perl = TRUE))[[1]]   # perl: ordered alternation, "NUMERIC: INTEGER" before "NUMERIC"
    if (length(tm) && nzchar(tm[1])) {
      after <- trimws(sub(paste0(".*", tm[1]), "", ln))
      v <- if (grepl("^[A-Za-z][A-Za-z0-9_]*$", after)) after else {
        cand <- c(L[i - 1], L[i + 1])
        cand <- cand[grepl("^[A-Za-z][A-Za-z0-9_]{0,31}$", cand) & !(cand %in% c("E", "TEXT", "LIST", "GPS"))]
        if (length(cand)) cand[1] else NA
      }
      if (is.na(v) || !is.null(var_ids[[v]])) next
      cls <- .pdf_types[[tm[2]]]
      it <- list(kind = "question", cls = sub("\\|.*$", "", cls), int = grepl("\\|int$", cls), var = v, id = nid(),
                 text = trimws(sub(tm[1], "", sub(paste0("\\b", v, "$"), "", ln), fixed = TRUE)),
                 parent = if (length(roster_stack)) roster_stack[[length(roster_stack)]] else cur_sec,
                 opts = list(), vals = list(), scope = 0L, cond = full_cond[[v]] %||% "",
                 linked = grepl("LINKED", tm[3] %||% ""), timestamp = grepl("CURRENT TIME", ln))
      cur_q <- push(it); var_ids[[v]] <- it$id; pending_fixed <- FALSE
      next
    }
    if (grepl("^SCOPE: ", ln) && !is.null(cur_q)) {
      items[[cur_q]]$scope <- switch(sub("^SCOPE: ", "", ln), HIDDEN = 3L, SUPERVISOR = 1L, IDENTIFYING = 2L, 0L)
      if (grepl("IDENTIFYING", ln)) items[[cur_q]]$featured <- TRUE
      next
    }
    if (grepl("^E [^0-9]", ln)) {
      tgt <- if (!is.null(cur_q)) cur_q else last_roster
      if (!is.null(tgt) && !nzchar(items[[tgt]]$cond)) {
        j <- unwrap(i, ln); items[[tgt]]$cond <- sub("^E ", "", j$x); skip <- j$skip
      }
      next
    }
    vm <- regmatches(ln, regexec("^([VW])[0-9]+ (.+)$", ln))[[1]]
    if (length(vm) && !is.null(cur_q)) {
      j <- unwrap(i, ln); vm[3] <- sub("^[VW][0-9]+ ", "", j$x); skip <- j$skip
      items[[cur_q]]$vals[[length(items[[cur_q]]$vals) + 1]] <- list(Expression = vm[3], Message = "", Severity = if (vm[2] == "W") 1L else 0L)
      next
    }
    if (grepl("^I ", ln)) { instr <- TRUE; next }
    om <- regmatches(ln, regexec("^(?:E )?(-?[0-9]{1,6}) (.+)$", ln, perl = TRUE))[[1]]
    if (length(om) && !cont) {
      if (pending_fixed && !is.null(last_roster)) {
        items[[last_roster]]$titles[[length(items[[last_roster]]$titles) + 1]] <- list(Value = as.numeric(om[2]), Title = om[3])
      } else if (!is.null(cur_q) && items[[cur_q]]$cls %in% c("SingleQuestion", "MultyOptionsQuestion")) {
        items[[cur_q]]$opts[[length(items[[cur_q]]$opts) + 1]] <- list(AnswerValue = om[2], AnswerText = om[3])
      }
    }
  }
  # assemble tree
  to_json <- function(k) {
    it <- items[[k]]
    kids <- which(vapply(items, function(x) identical(x$parent, k), TRUE))
    ch <- lapply(kids, to_json)
    if (it$kind == "section") return(list(`$type` = "Group", PublicKey = it$id, Title = it$title, IsRoster = FALSE, Children = ch))
    if (it$kind == "roster") {
      r <- list(`$type` = "Group", PublicKey = it$id, Title = it$title, VariableName = it$name %||% "", IsRoster = TRUE,
                ConditionExpression = it$cond, Children = ch)
      if (it$src == "question" && !is.null(var_ids[[it$trig]])) { r$RosterSizeSource <- 0; r$RosterSizeQuestionId <- var_ids[[it$trig]] }
      else { r$RosterSizeSource <- 1; r$FixedRosterTitles <- if (length(it$titles)) it$titles else list(list(Value = 1, Title = "1")) }
      return(r)
    }
    q <- list(`$type` = it$cls, PublicKey = it$id, VariableName = it$var, QuestionText = it$text,
              ConditionExpression = it$cond, ValidationConditions = it$vals, Answers = it$opts,
              IsInteger = it$int, QuestionScope = it$scope, Featured = isTRUE(it$featured), IsTimestamp = it$timestamp)
    if (it$cls == "TextListQuestion") q$MaxAnswerCount <- 40
    if (isTRUE(it$linked)) q$Answers <- list(list(AnswerValue = "1", AnswerText = "linked (unresolved in PDF)"), list(AnswerValue = "2", AnswerText = "linked (unresolved in PDF)"))
    q
  }
  tops <- which(vapply(items, function(x) is.na(x$parent[1]), TRUE))
  doc$Children <- lapply(tops, to_json)
  qn <- qn_from_document(doc, cat_dir = NULL, verbose = verbose)
  qn$warnings <- c(qn$warnings, "Questionnaire parsed from PDF: structure is heuristic -- verify, or use document.json")
  qn$source <- "pdf"
  qn
}
